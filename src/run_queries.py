import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "app"))

from charts import CHARTS
from data import get_connection, run_query, what_if_disqualified
from queries import Q12_STANDINGS, Q12_UPDATE, QUERIES


def fmt(v, width=60):
    if isinstance(v, list):
        s = "{" + ", ".join(str(x) for x in v[:8]) + (", ..." if len(v) > 8 else "") + "}"
    else:
        s = "" if v is None else str(v)
    return s if len(s) <= width else s[:width - 3] + "..."


def md_table(rows, limit=10):
    if not rows:
        return "_(no rows)_\n"
    cols = list(rows[0].keys())
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for r in rows[:limit]:
        out += "| " + " | ".join(fmt(r[c]).replace("|", "/") for c in cols) + " |\n"
    if len(rows) > limit:
        out += f"\n_... {len(rows)} rows in total_\n"
    return out


def main():
    md = ["# Query results (generated by src/run_queries.py)\n"]
    sql_file = ["-- =====================================================================",
                "-- 04_queries.sql - the 12 queries of the project with their default",
                "-- parameter values filled in (generated by src/run_queries.py).",
                "-- In the application the values are bound parameters chosen by the user.",
                "-- =====================================================================", ""]
    conn = get_connection()
    cur = conn.cursor()
    for q in QUERIES:
        params = q["defaults"]
        t0 = time.time()
        if q["id"] == "Q12":
            before, after, n = what_if_disqualified(**params)
            rows = [dict(before=f"{b['position']}. {b['driver']} {b['points']}",
                         after=f"{a['position']}. {a['driver']} {a['points']}") for b, a in zip(before, after)]
            CHARTS[q["id"]](before, after, path=ROOT / "docs" / "img" / "q12.png")
            sample = f"Rows updated: {n} (then ROLLBACK)\n\n" + md_table(rows)
            rendered = ("BEGIN;\n" + cur.mogrify(Q12_STANDINGS, params).decode() + ";\n"
                        + cur.mogrify(Q12_UPDATE, params).decode() + ";\n"
                        + cur.mogrify(Q12_STANDINGS, params).decode() + ";\nROLLBACK;")
        else:
            rows = run_query(q["sql"], params)
            CHARTS[q["id"]](rows, path=ROOT / "docs" / "img" / f"{q['id'].lower()}.png")
            sample = md_table(rows)
            rendered = cur.mogrify(q["sql"], params).decode().strip() + ";"
        ms = (time.time() - t0) * 1000
        print(f"{q['id']}  {len(rows):>4} rows  {ms:7.0f} ms  {q['title']}")
        md += [f"## {q['id']} - {q['title']}  (author: {q['author']})\n",
               f"**Question.** {q['question']}\n",
               f"**SQL features.** {q['features']}\n",
               f"**Parameters used.** `{params}`\n",
               f"```sql\n{q['sql'].strip()}\n```\n",
               "**Sample of the result.**\n", sample,
               f"\n**Why it is meaningful.** {q['why']}\n"]
        sql_file += [f"-- {q['id']} ({q['author']}): {q['title']}",
                     f"-- {q['question']}", rendered, ""]
    conn.close()
    (ROOT / "docs" / "query_results.md").write_text("\n".join(md), encoding="utf-8")
    (ROOT / "sql" / "04_queries.sql").write_text("\n".join(sql_file), encoding="utf-8")
    print("Written docs/query_results.md, sql/04_queries.sql and docs/img/q*.png")


if __name__ == "__main__":
    main()
