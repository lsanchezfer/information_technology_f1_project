import csv
import re
import sys
from datetime import datetime

from psycopg2 import sql

from db import RAW_DIR, ROOT, SQL_DIR, get_connection

FILES = [
    "seasons", "circuits", "status", "drivers", "constructors", "races",
    "results", "sprint_results", "qualifying", "pit_stops", "lap_times",
    "driver_standings", "constructor_standings", "constructor_results",
]


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def header(path):
    with open(path, newline="", encoding="utf-8") as f:
        return next(csv.reader(f))


def load_staging(cur):
    cur.execute("DROP SCHEMA IF EXISTS staging CASCADE; CREATE SCHEMA staging;")
    columns = {}
    for name in FILES:
        path = RAW_DIR / f"{name}.csv"
        cols = [snake(c) for c in header(path)]
        columns[name] = cols
        cur.execute(sql.SQL("CREATE TABLE staging.{} ({})").format(
            sql.Identifier(name),
            sql.SQL(", ").join(sql.SQL("{} TEXT").format(sql.Identifier(c)) for c in cols),
        ))
        # NULL is set to a string that never appears, so '\N' and '' stay visible.
        copy = sql.SQL(
            "COPY staging.{} FROM STDIN WITH (FORMAT csv, HEADER true, NULL '<<none>>')"
        ).format(sql.Identifier(name))
        with open(path, encoding="utf-8") as f:
            cur.copy_expert(copy.as_string(cur), f)
    return columns


def column_profile(cur, table, cols):
    out = []
    for c in cols:
        q = sql.SQL(
            "SELECT COUNT(*) AS total, "
            "COUNT(*) FILTER (WHERE {c} = '\\N') AS n_marker, "
            "COUNT(*) FILTER (WHERE {c} = '') AS n_empty, "
            "COUNT(DISTINCT {c}) AS n_distinct, "
            "MIN(LENGTH({c})) AS min_len, MAX(LENGTH({c})) AS max_len, "
            "(SELECT {c} FROM staging.{t} WHERE {c} <> '\\N' LIMIT 1) AS example "
            "FROM staging.{t}"
        ).format(c=sql.Identifier(c), t=sql.Identifier(table))
        cur.execute(q)
        out.append((c,) + cur.fetchone())
    return out


def run_checks(cur):
    text = (SQL_DIR / "01_profiling.sql").read_text(encoding="utf-8")
    blocks = re.split(r"^-- CHECK: ", text, flags=re.M)[1:]
    results = []
    for b in blocks:
        title, body = b.split("\n", 1)
        cur.execute(body)
        names = [d[0] for d in cur.description]
        results.append((title.strip(), body.strip(), names, cur.fetchall()))
    return results


def md_table(names, rows, limit=40):
    s = "| " + " | ".join(names) + " |\n|" + "---|" * len(names) + "\n"
    for r in rows[:limit]:
        s += "| " + " | ".join("" if v is None else str(v).replace("|", "/") for v in r) + " |\n"
    if len(rows) > limit:
        s += f"\n_{len(rows) - limit} more rows not shown_\n"
    return s


def main():
    conn = get_connection()
    try:
        with conn:
            with conn.cursor() as cur:
                cols = load_staging(cur)
                md = ["# Raw data profile (generated by src/profile_raw.py)\n",
                      f"Generated {datetime.now():%Y-%m-%d %H:%M}. All numbers come from SQL "
                      "on the schema `staging` (raw text copy of the CSV files).\n"]
                md.append("## Per-column profile\n")
                md.append("`\\N` is the null marker used by the source (Ergast). "
                          "`empty` counts empty strings.\n")
                for t in FILES:
                    prof = column_profile(cur, t, cols[t])
                    md.append(f"### {t}.csv - {prof[0][1]} rows\n")
                    md.append(md_table(["column", "rows", "\\N", "empty", "distinct",
                                        "min len", "max len", "example"], prof, 100))
                md.append("\n## Targeted checks (sql/01_profiling.sql)\n")
                for title, body, names, rows in run_checks(cur):
                    md.append(f"### {title}\n\n```sql\n{body}\n```\n")
                    md.append(md_table(names, rows))
        out = ROOT / "docs" / "profile_results.md"
        out.write_text("\n".join(md), encoding="utf-8")
        print(f"Profile written to {out}")
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
