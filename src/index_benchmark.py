import re

from db import ROOT, get_connection

TESTS = [
    ("idx_lap_times_driver",
     "All laps of one driver (lap_times, 589k rows)",
     "SELECT COUNT(*), MIN(lap_time_ms) FROM lap_times WHERE driver_id = %(driver_id)s",
     {"driver_id": 844}),
    ("idx_results_driver",
     "All results of one driver (results, 26k rows)",
     "SELECT COUNT(*), SUM(points) FROM results WHERE driver_id = %(driver_id)s",
     {"driver_id": 844}),
    ("lap_times_pkey",
     "Lap times of one race (lap_times primary key race_id, driver_id, lap)",
     "SELECT driver_id, MIN(lap_time_ms) FROM lap_times WHERE race_id = %(race_id)s GROUP BY driver_id",
     {"race_id": 1073}),
]


def explain(cur, sql_text, params, runs=5):
    best, plan = None, None
    for _ in range(runs):
        cur.execute("EXPLAIN (ANALYZE, BUFFERS OFF) " + sql_text, params)
        lines = [r[0] for r in cur.fetchall()]
        t = float(re.search(r"Execution Time: ([\d.]+) ms", lines[-1]).group(1))
        if best is None or t < best:
            best = t
            plan = next((ln.strip().lstrip("-> ").split("  (")[0] for ln in lines
                         if "Scan" in ln), lines[0])
    return best, plan


def main():
    conn = get_connection()
    md = ["# Index benchmark (generated by src/index_benchmark.py)\n",
          "Best of 5 runs of EXPLAIN ANALYZE. 'Without' = same transaction after DROP INDEX "
          "(or DROP CONSTRAINT for the primary key), then ROLLBACK.\n",
          "| query | index | with index (ms) | plan | without (ms) | plan | speed-up |",
          "|---|---|---|---|---|---|---|"]
    try:
        cur = conn.cursor()
        cur.execute("ANALYZE lap_times; ANALYZE results;")
        for index, label, sql_text, params in TESTS:
            t_with, p_with = explain(cur, sql_text, params)
            if index.endswith("_pkey"):
                cur.execute(f"ALTER TABLE lap_times DROP CONSTRAINT {index}")
            else:
                cur.execute(f"DROP INDEX {index}")
            t_without, p_without = explain(cur, sql_text, params)
            md.append(f"| {label} | {index} | {t_with:.2f} | {p_with} | {t_without:.2f} | "
                      f"{p_without} | x{t_without / t_with:.0f} |")
            print(f"{index:<22} with: {t_with:8.2f} ms   without: {t_without:8.2f} ms")
    finally:
        conn.rollback()           # the indexes come back
        conn.close()
    (ROOT / "docs" / "index_benchmark.md").write_text("\n".join(md) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
